# 터미널 창에 입력
# 라이브러리 설치 : pip install streamlit pandas
# Streamlit App 실행 : streamlit run .\02_basic_output.py

import streamlit as st
import pandas as pd

# =============================================================================
# 1. 제목 함수 (Headings and body text)
# =============================================================================
st.header("1. 제목 함수 (Headings and Body Text)")

# 메인 제목 설정 (페이지 상단에 큰 글씨로 표시)
st.title("st.title(): 페이지 제목")

# 대제목 (제목보다 작지만 눈에 띄는 헤더)
st.header("st.header(): 섹션 대제목")

# 소제목 (헤더보다 작은 크기의 제목)
st.subheader("st.subheader(): 섹션 소제목")

# =============================================================================
# 2. 마크다운 (Headings and body text)
# =============================================================================
st.divider()
st.header("2. 마크다운 (Headings and Body Text)")

# 마크다운 문법을 사용하여 서식이 있는 텍스트 출력
st.markdown("""
#### st.markdown(): 마크다운 서식 텍스트 출력

**텍스트 스타일:**  **굵게** / *기울임* / ~~취소선~~ / `인라인 코드`

**목록 작성:**
1. 첫 번째 항목
2. 두 번째 항목
- 불릿 포인트

> 💡 인용문도 표현 가능합니다!

**링크:** [Streamlit 공식문서](https://docs.streamlit.io)
""")

# =============================================================================
# 3. 기본 텍스트 (Formatted Text)
# =============================================================================
st.divider()
st.header("3. 기본 텍스트 (Formatted Text)")

# 일반 텍스트 출력 (포맷팅 없는 평문)
st.text("st.text(): 서식 없는 고정폭 텍스트 출력")

# 만능 출력 함수 - 텍스트, HTML, 마크다운, 데이터프레임 등 모든 것을 출력 가능
st.write("**st.write(): 만능 출력 함수 (텍스트, 데이터, 차트 등 모두 가능)**")

# 작은 글씨 캡션 (부연 설명, 출처 표시 등에 활용)
st.caption("st.caption(): 작은 글씨 캡션 (부연 설명, 출처 표시용)")

# =============================================================================
# 4. 코드 블록 (Formatted Text)
# =============================================================================
st.divider()
st.header("4. 코드 블록 (Formatted Text)")

# 구문 강조가 적용된 코드 블록 출력
st.write("**st.code(body, language):** 구문 강조된 코드 블록 표시")
st.code("""
def hello():
    print("Hello Streamlit!")
""", language='python')  # 언어 지정으로 구문 강조 활성화

# =============================================================================
# 5. 수학 공식 (Formatted Text)
# =============================================================================
st.divider()
st.header("5. 수학 공식 (Formatted Text)")

# LaTeX 문법으로 수학 공식 표시
st.write("**st.latex(body):** LaTeX 문법으로 수학 공식 표시")
st.latex(r"(x^2 + y^2 - 1)^3 - x^2 y^3 = 0")
st.caption("하트 방정식 (Heart Curve Equation)")

# =============================================================================
# 6. 색상 배지 (Formatted Text)
# =============================================================================
st.divider()
st.header("6. 색상 배지 (Formatted Text)")

# st.badge(): 색상 배지 표시 (Streamlit 1.51.0 이상)
# 주요 파라미터:
# - label: 배지에 표시할 텍스트
# - icon: 아이콘 (이모지 또는 :material/아이콘명: 형식)
# - color: 색상 (red, orange, yellow, blue, green, violet, gray, primary)
st.write("**st.badge(label, icon, color):** 색상 배지 표시")
st.badge("New")  # 기본 파란색
st.badge("Success", icon=":material/check:", color="green")  # 녹색 + 체크 아이콘
st.badge("Warning", icon="⚠️", color="orange")  # 주황색 + 이모지
st.badge("Error", icon=":material/close:", color="red")  # 빨간색

# =============================================================================
# 7. 상태 메시지 (Callouts)
# =============================================================================
st.divider()
st.header("7. 상태 메시지 (Callouts)")

# 성공 메시지 (녹색 배경)
st.success("st.success(): 성공/완료 알림 표시")

# 경고 메시지 (노란색 배경)
st.warning("st.warning(): 주의/경고 알림 표시")

# 에러 메시지 (빨간색 배경)
st.error("st.error(): 오류/실패 알림 표시")

# 정보 메시지 (파란색 배경)
st.info("st.info(): 정보/안내 알림 표시")

# =============================================================================
# 8. 데이터 표시 (Data Elements)
# =============================================================================
st.divider()
st.header("8. 데이터 표시 (Data Elements)")

# 샘플 데이터 딕셔너리 생성
data = {
    '이름': ['김철수', '이영희', '박민수'],
    '나이': [25, 30, 35],
    '도시': ['서울', '부산', '대구']
}

# 딕셔너리를 pandas 데이터프레임으로 변환
df = pd.DataFrame(data)

# =============================================================================
# 8-1. 인터랙티브 데이터프레임
# =============================================================================

st.subheader("데이터프레임")

# st.dataframe(): DataFrame 전용 함수
# 주요 파라미터:
# - height: 테이블 높이 (픽셀 단위)
# - width: 테이블 너비 (픽셀 단위 또는 'stretch'로 컨테이너 너비에 맞춤)
st.write("**st.dataframe(data, height, width):** 인터랙티브 테이블 (정렬, 검색, 크기 조절 가능)")
st.write("**용도:** 대용량 데이터 탐색, 사용자가 직접 정렬/필터링해야 할 때 사용")
st.dataframe(df, height=200, width=500)

# st.write(): 만능 함수 - DataFrame 출력시 옵션 설정 불가!
st.write("**st.write(df):** DataFrame도 출력 가능 (단, 옵션 설정 불가)")
st.write(df)

# =============================================================================
# 8-2. 정적 테이블
# =============================================================================

st.subheader("📊 정적 테이블")
# 상호작용 불가능한 고정된 형태의 테이블
st.write("**st.table(data):** 정적 테이블 (정렬, 검색 불가)")
st.table(df)

# =============================================================================
# 9. 메트릭 카드 (Data Elements)
# =============================================================================
st.divider()
st.header("9. 메트릭 카드 (Data Elements)")
st.write("**st.metric(label, value, delta):** KPI 지표 카드 표시 (값 + 변화량)")

# 화면을 3개의 열로 분할하여 레이아웃 구성
col1, col2, col3 = st.columns(3)

# 첫 번째 열: 사용자 수 메트릭
with col1:
    # label: 메트릭 이름, value: 현재 값, delta: 변화량 (양수=녹색, 음수=빨간색)
    st.metric(label="총 사용자", value="1,234", delta="+12%")

# 두 번째 열: 매출 메트릭
with col2:
    # delta에 음수나 퍼센트를 넣으면 빨간색으로 표시됨
    st.metric(label="매출", value="₩12,345,678", delta="-2.3%")

# 세 번째 열: 성장률 메트릭
with col3:
    # delta에 양수를 넣으면 녹색으로 표시됨
    st.metric(label="성장률", value="15.2%", delta="1.2%")